//Arithmetic Operators
//Arithmetic operators are used to perform basic mathematical operations.

let a = 12;
let b = 13;
let sum = a + b;
console.log(sum);

let diff = a - b;
console.log(diff);

let product = a * b;
console.log(product);

let division = a / b;
console.log(division);

let modulo = a % b;                                          //remainder operator
console.log(modulo);                                         //12 % 5 = 2

let exponentiation = a ** b;                                //power operator
console.log(exponentiation);                                //2**3 = 8
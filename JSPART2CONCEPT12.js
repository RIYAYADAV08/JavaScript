//Switch Statement → Used when we have some fixed values that we need to compare to.
let color = "red";
switch(color) {
    case "red":
        console.log("stop");
        break;
    case "yellow" :
        console.log("wait");
        break;
    case "green":
        console.log("go");
        break;
    default:
        console.log("Broken Light");
}


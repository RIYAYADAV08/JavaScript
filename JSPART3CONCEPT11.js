//Array Methods
//push - add to end 
//pop- delete from end 
//unshift- add to start
//shift- delete from start

let cars = ["thar", "maruti", "suzuki"];
cars.push("ferrari");
console.log(cars);
cars.pop();
console.log(cars);
cars.unshift("alto");
console.log(cars);
cars.shift();
console.log(cars);

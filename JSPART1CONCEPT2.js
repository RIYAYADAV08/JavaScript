//Arithmetic Operators
//They are used to perform arithmetic operations.

let a = 24;
let b = 10;
let sum = a + b;
console.log(sum);

let diff = a - b;
console.log(diff);

let product = a * b;
console.log(product);

let quotient = a / b;
console.log(quotient);

let exponentiation = a ** b;                                                    //Power operator 2**3 = 8
console.log(exponentiation);

let modulo = a % b;                                                             //Remainder Operator 12%5 = 2
console.log(modulo);
//JavaScript
//JavaScript is a high level, interpreted programming language primarily used to add interactivity and dynamic behaviour to web pages. It works with HTML and CSS to build modern web applications and can also be used for backend development through node.js.

//Is Java and JavaScript are same?
//No, Java and JavaScript are different programming languages. Java is mainly used for backend development, while JavaScript is primarily used for web development.

//Why do we need JavaScript?
//JavaScript is used to make web pages dynamic and interactive such as form validations, animations, button Click events and API calls.

//console.log()- It is used to display output in console.It is used for testing and debugging JavaScript Code.

//Features of JavaScript
//JavaScript is a high-level language as it is easy to read and write and we don't need to deal with low-level machine details.
//JavaScript is dynamically typed as the type of a variable is decided automatically at runtime.
//JavaScript is object-oriented language as it allows us to organize data and functionality using classes.
//JavaScript is event-driven as it can respond to events like clicks, key presses and mouse movements.
//JavaScript is cross-platform language as it can on different operating systems and web-browsers.
//JavaScript is interpreted language as it is executed at runtime by a JavaScript Engine.Modern Engine also use JIT(Just-in-time) compilation for better performance.

//Advantages of JavaScript
//Fast Execution
//Easy to learn
//Versatile
//Light-weight
//PLatform-independent

//Disadvantages of JavaScript
//Security Issues
//Difficult debugging

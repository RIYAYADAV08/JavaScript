//Unary operator
//Unary operator is the operator that work on only one operand(one value or one variable).

let a = 10;
a++;
console.log(a);
a++;
console.log(a);

let b = 9;
b--;
console.log(b);
b--;
console.log(b);
b--;
console.log(b);
b--;
console.log(b);

//There are two types also:
//1.Pre-increment- First increment the value and then return the updated value.
let d = 5;
let newd = ++d;
console.log(d);
console.log(newd);

//2.Post-increment- First returns the value then increments it.
let e = 10;
let newe = e++;
console.log(e);
console.log(newe);
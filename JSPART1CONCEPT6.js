//Arithmetic operators
//They are used to perform arithmetic operations.

let a = 12;
let b = 10;
let sum = a + b;
console.log(sum);

let diff = a - b;
console.log(diff);

let multiply = a * b;
console.log(multiply);

let division = a / b;
console.log(division);

let modulo = a % b;                                               //remainder operator   16 % 3 = 1
console.log(modulo);

let exponentiation = a ** b;                                      //power operator   2**3 = 8
console.log(exponentiation);
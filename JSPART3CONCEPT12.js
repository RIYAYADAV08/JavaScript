//indexOf
//It returns the index of the first occurence of the specified value in an array.
let primary = ["Yellow", "Green", "Blue"];

console.log(primary.indexOf("Green"));
console.log(primary.indexOf("green"));
console.log(primary.indexOf("Red"));


//includes
//It checks whether an element exists in the array and returns true of false.
console.log(primary.includes("Yellow"));
console.log(primary.includes("Red"));


